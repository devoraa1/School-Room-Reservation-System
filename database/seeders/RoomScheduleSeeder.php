    public function run(): void
    {
        // Start clean so old rows never linger.
        RoomSchedule::query()->delete();

        foreach (self::SCHEDULE as $roomName => $blocks) {
            $room = Room::where('name', $roomName)->first();

            if (! $room) {
                continue;
            }

            RoomSchedule::insert(array_map(fn ($b) => [
                'room_id' => $room->id,
                'day_of_week' => $b[0],
                'start_time' => $b[1],
                'end_time' => $b[2],
                'course_section' => $b[3],
                'instructor' => $b[4],
            ], $blocks));
        }
    }
